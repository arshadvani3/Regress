    """Write `<name>.yaml` and `test_<name>.py` into `directory`.

    Returns (yaml_path, pytest_path). Overwrites any existing files with
    the same name — regenerating an eval for an issue replaces it rather
    than accumulating duplicates.
    """
    directory.mkdir(parents=True, exist_ok=True)
    yaml_path = directory / f"{eval_.name}.yaml"
    pytest_path = directory / f"test_{eval_.name.replace('-', '_')}.py"

    yaml_path.write_text(yaml.safe_dump(eval_to_dict(eval_), sort_keys=False))
    pytest_path.write_text(
        _PYTEST_MODULE_TEMPLATE.format(
            yaml_name=yaml_path.name,
            test_name=eval_.name.replace("-", "_"),
        )
    )
    return yaml_path, pytest_path
